"""Emit Remotion-consumable timeline artifacts from the narration manifest."""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Iterable

from .timeline import Timeline, remotion_frames


def resolve_anchor(timeline: Timeline, segment_id: str, offset_ms: int) -> dict[str, int | str]:
    if not isinstance(offset_ms, int) or isinstance(offset_ms, bool) or offset_ms < 0:
        raise ValueError("anchor offset_ms must be a non-negative integer")
    if not isinstance(segment_id, str) or not segment_id:
        raise ValueError("anchor segment_id must be a non-empty string")
    cue = next((cue for cue in timeline.cues if cue.id == segment_id), None)
    if cue is None:
        raise ValueError(f"Unknown narration segment: {segment_id}")
    resolved = cue.start_ms + offset_ms
    clamped = False
    if resolved > cue.end_ms:
        resolved = cue.end_ms
        clamped = True
    return {"segment_id": segment_id, "offset_ms": offset_ms, "time_ms": resolved, "clamped": clamped}


def _ts_literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def generate_remotion_timeline(timeline: Timeline, output_dir: Path, *, anchors: Iterable[dict] = (), audio_duration_ms: int | None = None) -> dict:
    if audio_duration_ms is not None and audio_duration_ms <= 0:
        raise ValueError("audio_duration_ms must be positive")
    frames = remotion_frames(timeline, timeline.fps)
    resolved_anchors = [resolve_anchor(timeline, a["segment_id"], int(a["offset_ms"])) for a in anchors]
    end_ms = max(timeline.duration_ms, audio_duration_ms or 0, max((int(a["time_ms"]) for a in resolved_anchors), default=0))
    total_duration_ms = end_ms + timeline.tail_padding_ms
    duration_frames = math.ceil(total_duration_ms * timeline.fps / 1000)
    cues = []
    by_id = {cue.id: cue for cue in timeline.cues}
    for frame in frames:
        cue = by_id[frame["id"]]
        cues.append({**frame, "text": cue.display_text, "segmentId": cue.id})
    result = {
        "schema_version": timeline.version,
        "fps": timeline.fps,
        "durationInFrames": duration_frames,
        "audioDurationMs": audio_duration_ms,
        "cues": cues,
        "anchors": resolved_anchors,
    }
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "timeline.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["// AUTO-GENERATED by p103.remotion; do not edit.",
             f"export const FPS = {timeline.fps};",
             f"export const DURATION_IN_FRAMES = {duration_frames};",
             f"export const CUES = {_ts_literal(cues)} as const;",
             f"export const SEGMENT_ANCHORS = {_ts_literal(resolved_anchors)} as const;",
             ""]
    (output_dir / "timeline.ts").write_text("\n".join(lines), encoding="utf-8")
    return result
